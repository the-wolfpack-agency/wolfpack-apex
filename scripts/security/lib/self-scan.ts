/**
 * Rules for the AgenticQA security self-scan (security-self-scan.yml).
 *
 * Three things went wrong with the inline Python this replaces, and each is
 * a rule here:
 *
 * 1. THE BASELINE ONLY MOVES BY A REVIEWED COMMIT. The workflow used to
 *    rewrite `.agenticqa/scan-baseline.json` from the current findings on
 *    every push to main, so any new finding became "known" the moment it
 *    landed and the gate could never go red. Now the gate only reads the
 *    baseline; `baselineFromScan` is called from the CLI's `baseline`
 *    command, run by a person, and its output is committed through a PR.
 *
 * 2. COUNTS ONLY IN PUBLIC. wolfpack-apex is public, so its run logs, job
 *    summaries, PR comments and artifacts are world-readable. A findings
 *    table there is a list of where to attack. Rendering is redacted unless
 *    the workflow states the repository is private (see `isRedacted` in
 *    report.ts), and the job outputs that carry data between jobs are
 *    numbers only.
 *
 * 3. A SCANNER THAT DID NOT RUN IS NOT A PASS. A key scanner that reports
 *    `status: error` or is missing from the output, and a pentest phase that
 *    returned nothing, are counted as errors and fail the gate.
 */
import { createHash } from "node:crypto";

/** The six scanners whose critical/high findings gate the build. */
export const KEY_SCANNERS = [
  "auth_bypass",
  "idor",
  "jwt_security",
  "rate_limit",
  "error_disclosure",
  "security_headers",
] as const;

/** A finding as emitted by AgenticQA's scanners (fields vary by scanner). */
export interface ScanFinding {
  file?: unknown;
  cwe?: unknown;
  rule_id?: unknown;
  evidence?: unknown;
  message?: unknown;
  severity?: unknown;
  line?: unknown;
}

interface ScannerEntry {
  status?: string;
  error?: string;
  result?: { findings?: ScanFinding[]; total_findings?: number; findings_count?: number; critical?: number };
}

/** Shape of `run_client_scan.py --output` (only the fields we read). */
export interface ScanResults {
  summary?: { total_findings?: number; total_critical?: number; risk_level?: string };
  scanners?: Record<string, ScannerEntry>;
}

export interface Baseline {
  finding_hashes: string[];
  total: number;
  generated_at: string;
  /** Who/why, so a baseline change reads as a decision in review. */
  note?: string;
}

const SNIPPET_CAP = 160;

/** Python's `str(x or "")` for the JSON values a finding can carry. */
function pyStr(v: unknown): string {
  if (v === null || v === undefined || v === false || v === "" || v === 0) return "";
  return String(v);
}

/**
 * Port of agenticqa.security.finding_fingerprint.fingerprint. The committed
 * baseline was generated by the Python function, so this must produce the
 * same 16 hex characters for the same finding. Pinned by reference vectors
 * computed with the Python original in the unit test.
 */
export function fingerprint(f: ScanFinding): string {
  const file = pyStr(f.file);
  const cwe = pyStr(f.cwe);
  const rule = pyStr(f.rule_id);
  const raw = pyStr(f.evidence) || pyStr(f.message);
  // Python slices by code point, not UTF-16 unit.
  const snippet = Array.from(raw.replace(/\s+/gu, " ").trim().toLowerCase()).slice(0, SNIPPET_CAP).join("");
  return createHash("sha256").update(`${file}|${cwe}|${rule}|${snippet}`, "utf8").digest("hex").slice(0, 16);
}

export interface ScannerRow {
  name: string;
  status: "ok" | "error" | "missing";
  findings: number;
  critical: number;
}

export interface NewFinding {
  hash: string;
  scanner: string;
  severity: string;
  file: string;
  rule: string;
  message: string;
}

export interface StaticGate {
  totalFindings: number;
  totalCritical: number;
  riskLevel: string;
  rows: ScannerRow[];
  /** Distinct fingerprints across the key scanners. */
  keyFindings: number;
  baselineSize: number;
  /** Fingerprints present now and absent from the baseline. */
  newFindings: NewFinding[];
  newCriticalHigh: number;
  /** Baseline entries no longer present (fixed, or moved and re-fingerprinted). */
  resolved: number;
  /** Key scanners that errored or were missing: the gate cannot vouch for them. */
  scannerErrors: string[];
}

function num(v: unknown): number {
  return typeof v === "number" && Number.isFinite(v) ? v : 0;
}

export function evaluateStatic(scan: ScanResults, baselineHashes: Iterable<string>): StaticGate {
  const baseline = new Set(baselineHashes);
  const scanners = scan.scanners ?? {};
  const rows: ScannerRow[] = [];
  const current = new Map<string, NewFinding>();
  const scannerErrors: string[] = [];

  for (const name of KEY_SCANNERS) {
    const s = scanners[name];
    if (!s) {
      rows.push({ name, status: "missing", findings: 0, critical: 0 });
      scannerErrors.push(`${name}: not in scan output`);
      continue;
    }
    if (s.status !== "ok") {
      rows.push({ name, status: "error", findings: 0, critical: 0 });
      scannerErrors.push(`${name}: status ${s.status ?? "unknown"}`);
      continue;
    }
    const r = s.result ?? {};
    const list = Array.isArray(r.findings) ? r.findings : [];
    rows.push({ name, status: "ok", findings: num(r.total_findings ?? r.findings_count ?? list.length), critical: num(r.critical) });
    for (const f of list) {
      const hash = fingerprint(f);
      if (current.has(hash)) continue;
      current.set(hash, {
        hash,
        scanner: name,
        severity: pyStr(f.severity).toLowerCase() || "unknown",
        file: pyStr(f.file),
        rule: pyStr(f.rule_id),
        message: pyStr(f.message),
      });
    }
  }

  const newFindings = [...current.values()].filter((f) => !baseline.has(f.hash));
  let resolved = 0;
  for (const h of baseline) if (!current.has(h)) resolved++;

  return {
    totalFindings: num(scan.summary?.total_findings),
    totalCritical: num(scan.summary?.total_critical),
    riskLevel: typeof scan.summary?.risk_level === "string" ? scan.summary.risk_level : "unknown",
    rows,
    keyFindings: current.size,
    baselineSize: baseline.size,
    newFindings,
    newCriticalHigh: newFindings.filter((f) => f.severity === "critical" || f.severity === "high").length,
    resolved,
    scannerErrors,
  };
}

/** Numbers only: safe for job outputs and public summaries. */
export function staticOutputs(g: StaticGate): Record<string, number | string> {
  return {
    total_findings: g.totalFindings,
    total_critical: g.totalCritical,
    risk_level: /^[a-z]+$/.test(g.riskLevel) ? g.riskLevel : "unknown",
    key_findings: g.keyFindings,
    baseline_size: g.baselineSize,
    new_findings: g.newFindings.length,
    new_critical_high: g.newCriticalHigh,
    resolved: g.resolved,
    scanner_errors: g.scannerErrors.length,
  };
}

function cell(s: string): string {
  return s.replace(/\\/g, "\\\\").replace(/\|/g, "\\|").replace(/\r?\n/g, " ");
}

const PUBLIC_NOTE =
  "Details are withheld because this repository is public. Run the scanner locally for the full list (docs/security/self-scan.md).";

export function renderStatic(g: StaticGate, redacted: boolean): string {
  const out: string[] = ["## AgenticQA Security Scan", ""];
  out.push("| Scanner | Findings | Critical | Status |", "|---------|----------|----------|--------|");
  for (const r of g.rows) {
    const status = r.status === "ok" ? (r.critical === 0 ? "PASS" : "FAIL") : r.status === "error" ? "ERROR" : "MISSING";
    const show = r.status === "ok";
    out.push(`| ${r.name.replace(/_/g, " ")} | ${show ? r.findings : "-"} | ${show ? r.critical : "-"} | ${status} |`);
  }
  out.push("");
  out.push(
    `**Baseline:** ${g.baselineSize} known, ${g.newFindings.length} new (${g.newCriticalHigh} critical/high), ${g.resolved} no longer present`,
  );
  out.push("");
  out.push(`**Overall:** ${g.totalFindings} findings, ${g.totalCritical} critical, risk=${g.riskLevel}`);
  if (g.scannerErrors.length) {
    out.push("", `**${g.scannerErrors.length} key scanner(s) did not report.** The gate fails until they do.`);
  }
  out.push("");
  if (redacted) {
    out.push(PUBLIC_NOTE, "");
    return out.join("\n");
  }
  if (g.scannerErrors.length) {
    out.push("### Scanner errors", "");
    for (const e of g.scannerErrors) out.push(`- ${e}`);
    out.push("");
  }
  if (g.newFindings.length) {
    out.push("### New findings (not in the baseline)", "");
    out.push("| Severity | Scanner | File | Rule | Message | Fingerprint |", "| --- | --- | --- | --- | --- | --- |");
    for (const f of g.newFindings) {
      out.push(`| ${cell(f.severity)} | ${f.scanner} | ${cell(f.file)} | ${cell(f.rule)} | ${cell(f.message)} | ${f.hash} |`);
    }
    out.push("");
  }
  return out.join("\n");
}

/** Build the baseline a person reviews and commits. Never called by CI. */
export function baselineFromScan(scan: ScanResults, note: string, now: Date = new Date()): Baseline {
  const hashes = new Set<string>();
  for (const name of KEY_SCANNERS) {
    const s = scan.scanners?.[name];
    if (s?.status !== "ok") continue;
    for (const f of s.result?.findings ?? []) hashes.add(fingerprint(f));
  }
  const finding_hashes = [...hashes].sort();
  return { finding_hashes, total: finding_hashes.length, generated_at: now.toISOString(), note };
}

export function parseBaseline(text: string): string[] {
  const data = JSON.parse(text) as Partial<Baseline>;
  if (!Array.isArray(data.finding_hashes) || !data.finding_hashes.every((h) => typeof h === "string")) {
    throw new Error("baseline has no finding_hashes array");
  }
  return data.finding_hashes;
}

// ── Pentest phase (self_hack.py --phase pentest) ────────────────────────────

export interface PentestGate {
  /** False when phase 2 did not run (agent missing or crashed): an error, not a pass. */
  ran: boolean;
  findings: number;
  confirmed: number;
  confirmedCriticalHigh: number;
}

interface PentestFinding {
  confirmed?: boolean;
  status?: string;
  severity?: string;
}

/**
 * The old check read `summary.total_critical`, a key self_hack.py's report
 * does not have, so it printed "0 confirmed critical" on every run whatever
 * the pentest found. The confirmed results live under `phase2`.
 */
export function evaluatePentest(report: unknown): PentestGate {
  const phase2 = (report as { phase2?: unknown } | null)?.phase2 as
    | { findings?: PentestFinding[]; confirmed_vulnerabilities?: number; total_findings?: number }
    | null
    | undefined;
  if (!phase2 || typeof phase2 !== "object") return { ran: false, findings: 0, confirmed: 0, confirmedCriticalHigh: 0 };
  const list = Array.isArray(phase2.findings) ? phase2.findings : [];
  const isConfirmed = (f: PentestFinding) => f.confirmed === true || f.status === "confirmed";
  const confirmedList = list.filter(isConfirmed);
  const confirmed = Math.max(num(phase2.confirmed_vulnerabilities), confirmedList.length);
  const confirmedCriticalHigh = confirmedList.filter((f) => ["critical", "high"].includes((f.severity ?? "").toLowerCase())).length;
  return {
    ran: true,
    findings: num(phase2.total_findings) || list.length,
    confirmed,
    // A confirmed count without per-finding severity still has to fail.
    confirmedCriticalHigh: confirmedCriticalHigh || (confirmed > 0 && confirmedList.length === 0 ? confirmed : 0),
  };
}

// ── Combined report (scan-summary job) ──────────────────────────────────────

export interface CombinedInput {
  staticResult: string;
  pentestResult: string;
  dependencyResult: string;
  totalFindings: string;
  totalCritical: string;
  riskLevel: string;
  newFindings: string;
  newCriticalHigh: string;
  scannerErrors: string;
  pentestRan: string;
  pentestConfirmed: string;
  pentestConfirmedCriticalHigh: string;
  depHigh: string;
  depCritical: string;
}

/** Job outputs are strings and can be empty (job skipped). Keep digits only. */
export function asCount(v: string | undefined): string {
  return v && /^\d+$/.test(v) ? v : "-";
}

/**
 * Built from job outputs that carry numbers only, so it is safe in a public
 * summary, PR comment and issue body whatever the scanners found.
 */
export function renderCombined(i: CombinedInput): string {
  const risk = /^[a-z]+$/.test(i.riskLevel) ? i.riskLevel : "unknown";
  const job = (s: string) => (/^[a-z_]+$/.test(s) ? s : "unknown");
  const pentest = i.pentestRan === "true" ? `${asCount(i.pentestConfirmed)} confirmed (${asCount(i.pentestConfirmedCriticalHigh)} critical/high)` : "did not run";
  return [
    "## AgenticQA Security Scan",
    "",
    "| Job | Result | Counts |",
    "| --- | --- | --- |",
    `| Static scan | ${job(i.staticResult)} | ${asCount(i.totalFindings)} findings, ${asCount(i.totalCritical)} critical, risk=${risk}; ${asCount(i.newFindings)} new vs baseline (${asCount(i.newCriticalHigh)} critical/high); ${asCount(i.scannerErrors)} scanner errors |`,
    `| Pentest validation | ${job(i.pentestResult)} | ${pentest} |`,
    `| Dependency audit | ${job(i.dependencyResult)} | ${asCount(i.depHigh)} high, ${asCount(i.depCritical)} critical (production dependencies) |`,
    "",
    "Counts only. Finding details never go to this public repository's logs, summaries, comments or artifacts; see docs/security/self-scan.md to see them locally.",
    "",
  ].join("\n");
}
