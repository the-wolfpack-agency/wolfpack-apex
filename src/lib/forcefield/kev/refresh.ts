/**
 * Pure core of the KEV refresh (scripts/kev-refresh.ts does the I/O).
 *
 * Deterministic by construction: the tracked CVE set is sorted, every field is
 * copied verbatim from the feed, and the rendered file has a fixed layout, so
 * the same feed + tracked set always produces byte-identical output. A tracked
 * CVE that is NOT in the feed is an error, never a guess: this is what stops a
 * mistyped or invented CVE id from shipping.
 *
 * Drift (`--check`) compares ENTRIES only, not the catalog version. CISA adds
 * entries most weekdays, so a version-sensitive check would fail daily for
 * reasons that change nothing we ship; an entry we track that changed or left
 * the catalog is real drift.
 */
import type { KevEntry, KevSnapshot } from "./types";

export const KEV_FEED_URL = "https://www.cisa.gov/sites/default/files/feeds/known_exploited_vulnerabilities.json";

const CVE_RE = /^CVE-\d{4}-\d{4,}$/;

export interface KevFeed {
  catalogVersion: string;
  dateReleased: string;
  vulnerabilities: Array<Record<string, unknown>>;
}

export type FeedResult = { ok: true; feed: KevFeed } | { ok: false; error: string };

/** Validate the untrusted feed shape. Never throws. */
export function parseKevFeed(raw: unknown): FeedResult {
  if (!raw || typeof raw !== "object") return { ok: false, error: "feed is not an object" };
  const r = raw as Record<string, unknown>;
  if (typeof r.catalogVersion !== "string" || !r.catalogVersion) return { ok: false, error: "feed has no catalogVersion" };
  if (typeof r.dateReleased !== "string" || !r.dateReleased) return { ok: false, error: "feed has no dateReleased" };
  if (!Array.isArray(r.vulnerabilities) || r.vulnerabilities.length === 0) return { ok: false, error: "feed has no vulnerabilities" };
  return {
    ok: true,
    feed: {
      catalogVersion: r.catalogVersion,
      dateReleased: r.dateReleased,
      vulnerabilities: r.vulnerabilities.filter((v): v is Record<string, unknown> => !!v && typeof v === "object"),
    },
  };
}

function str(v: unknown): string {
  return typeof v === "string" ? v.trim() : "";
}

/** Sorted, de-duplicated, validated tracked set. Throws on a malformed id. */
export function normalizeTracked(ids: Iterable<string>): string[] {
  const out = new Set<string>();
  for (const id of ids) {
    const v = (id ?? "").trim().toUpperCase();
    if (!CVE_RE.test(v)) throw new Error(`not a CVE id: ${JSON.stringify(id)}`);
    out.add(v);
  }
  return [...out].sort();
}

export type BuildResult =
  | { ok: true; snapshot: KevSnapshot }
  | { ok: false; error: string; missing: string[] };

/** Build the snapshot for the tracked set from a validated feed. */
export function buildSnapshot(feed: KevFeed, tracked: Iterable<string>): BuildResult {
  const ids = normalizeTracked(tracked);
  const byId = new Map<string, Record<string, unknown>>();
  for (const v of feed.vulnerabilities) {
    const id = str(v.cveID).toUpperCase();
    if (id) byId.set(id, v);
  }
  const missing = ids.filter((id) => !byId.has(id));
  if (missing.length > 0) {
    return { ok: false, error: `tracked CVE(s) not in the KEV feed: ${missing.join(", ")}`, missing };
  }
  const entries: Record<string, KevEntry> = {};
  for (const id of ids) {
    const v = byId.get(id)!;
    entries[id] = {
      cveId: id,
      vendorProject: str(v.vendorProject),
      product: str(v.product),
      vulnerabilityName: str(v.vulnerabilityName),
      dateAdded: str(v.dateAdded),
      knownRansomware: str(v.knownRansomwareCampaignUse).toLowerCase() === "known",
    };
  }
  return {
    ok: true,
    snapshot: { source: KEV_FEED_URL, catalogVersion: feed.catalogVersion, dateReleased: feed.dateReleased, entries },
  };
}

/** The ids whose entry differs between two snapshots (added, removed, changed). */
export function diffEntries(a: KevSnapshot["entries"], b: KevSnapshot["entries"]): string[] {
  const ids = new Set([...Object.keys(a), ...Object.keys(b)]);
  const out: string[] = [];
  for (const id of [...ids].sort()) {
    if (JSON.stringify(a[id] ?? null) !== JSON.stringify(b[id] ?? null)) out.push(id);
  }
  return out;
}

/** Render the checked-in TypeScript snapshot file. Fixed layout, sorted keys. */
export function renderSnapshotFile(s: KevSnapshot): string {
  const lines: string[] = [
    "/**",
    " * GENERATED by scripts/kev-refresh.ts from the public CISA Known Exploited",
    " * Vulnerabilities feed. Do not edit by hand: run `npm run kev:refresh`, review",
    " * the diff, commit. `npm run kev:check` fails when a tracked entry drifts.",
    " *",
    " * Holds only the CVEs this codebase references (Forcefield CVE probe rules and",
    " * the platform-scan edge-device product map). Never fetched at runtime.",
    " */",
    'import type { KevSnapshot } from "./types";',
    "",
    "export const KEV_SNAPSHOT: KevSnapshot = {",
    `  source: ${JSON.stringify(s.source)},`,
    `  catalogVersion: ${JSON.stringify(s.catalogVersion)},`,
    `  dateReleased: ${JSON.stringify(s.dateReleased)},`,
    "  entries: {",
  ];
  for (const id of Object.keys(s.entries).sort()) {
    const e = s.entries[id];
    lines.push(`    ${JSON.stringify(id)}: {`);
    lines.push(`      cveId: ${JSON.stringify(e.cveId)},`);
    lines.push(`      vendorProject: ${JSON.stringify(e.vendorProject)},`);
    lines.push(`      product: ${JSON.stringify(e.product)},`);
    lines.push(`      vulnerabilityName: ${JSON.stringify(e.vulnerabilityName)},`);
    lines.push(`      dateAdded: ${JSON.stringify(e.dateAdded)},`);
    lines.push(`      knownRansomware: ${e.knownRansomware},`);
    lines.push("    },");
  }
  lines.push("  },", "};", "");
  return lines.join("\n");
}
