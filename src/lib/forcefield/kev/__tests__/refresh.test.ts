/**
 * The KEV refresh core: feed validation, the never-invent rule (a tracked id
 * missing from the feed fails), deterministic rendering, and entry-only drift.
 * Synthetic feed fixtures only; no network.
 */
import { buildSnapshot, diffEntries, normalizeTracked, parseKevFeed, renderSnapshotFile, KEV_FEED_URL } from "../refresh";

const FEED = {
  catalogVersion: "2099.01.02",
  dateReleased: "2099-01-02T00:00:00.000Z",
  vulnerabilities: [
    { cveID: "CVE-2099-0002", vendorProject: "Acme", product: "Gate", vulnerabilityName: "Acme Gate Bug", dateAdded: "2099-01-01", knownRansomwareCampaignUse: "Known" },
    { cveID: "CVE-2099-0001", vendorProject: " Acme ", product: "Portal", vulnerabilityName: "Acme Portal Bug", dateAdded: "2098-12-31", knownRansomwareCampaignUse: "Unknown" },
  ],
};

describe("parseKevFeed", () => {
  it("accepts a well-formed feed", () => {
    expect(parseKevFeed(FEED).ok).toBe(true);
  });
  it.each([
    [null, "not an object"],
    [{ dateReleased: "x", vulnerabilities: [{}] }, "catalogVersion"],
    [{ catalogVersion: "x", vulnerabilities: [{}] }, "dateReleased"],
    [{ catalogVersion: "x", dateReleased: "y", vulnerabilities: [] }, "vulnerabilities"],
  ])("rejects a malformed feed (%#)", (raw, msg) => {
    const r = parseKevFeed(raw);
    expect(r.ok).toBe(false);
    if (!r.ok) expect(r.error).toContain(msg);
  });
});

describe("normalizeTracked", () => {
  it("sorts, uppercases and de-duplicates", () => {
    expect(normalizeTracked(["cve-2099-0002", "CVE-2099-0001", "CVE-2099-0002"])).toEqual(["CVE-2099-0001", "CVE-2099-0002"]);
  });
  it("throws on a malformed id", () => {
    expect(() => normalizeTracked(["CVE-99-1"])).toThrow(/not a CVE id/);
  });
});

describe("buildSnapshot", () => {
  const feed = (parseKevFeed(FEED) as { ok: true; feed: Parameters<typeof buildSnapshot>[0] }).feed;

  it("copies the tracked entries verbatim (trimmed) and maps ransomware use", () => {
    const r = buildSnapshot(feed, ["CVE-2099-0002", "CVE-2099-0001"]);
    expect(r.ok).toBe(true);
    if (!r.ok) return;
    expect(r.snapshot.source).toBe(KEV_FEED_URL);
    expect(r.snapshot.catalogVersion).toBe("2099.01.02");
    expect(Object.keys(r.snapshot.entries)).toEqual(["CVE-2099-0001", "CVE-2099-0002"]);
    expect(r.snapshot.entries["CVE-2099-0001"]).toEqual({
      cveId: "CVE-2099-0001", vendorProject: "Acme", product: "Portal", vulnerabilityName: "Acme Portal Bug", dateAdded: "2098-12-31", knownRansomware: false,
    });
    expect(r.snapshot.entries["CVE-2099-0002"].knownRansomware).toBe(true);
  });

  it("fails (never invents) when a tracked id is not in the feed", () => {
    const r = buildSnapshot(feed, ["CVE-2099-0001", "CVE-2099-9999"]);
    expect(r.ok).toBe(false);
    if (!r.ok) expect(r.missing).toEqual(["CVE-2099-9999"]);
  });

  it("renders byte-identical output for the same input (deterministic)", () => {
    const a = buildSnapshot(feed, ["CVE-2099-0002", "CVE-2099-0001"]);
    const b = buildSnapshot(feed, ["CVE-2099-0001", "CVE-2099-0002"]);
    if (!a.ok || !b.ok) throw new Error("build failed");
    expect(renderSnapshotFile(a.snapshot)).toBe(renderSnapshotFile(b.snapshot));
    expect(renderSnapshotFile(a.snapshot)).toContain("GENERATED by scripts/kev-refresh.ts");
  });
});

describe("diffEntries", () => {
  const base = { "CVE-2099-0001": { cveId: "CVE-2099-0001", vendorProject: "A", product: "P", vulnerabilityName: "N", dateAdded: "2099-01-01", knownRansomware: false } };
  it("reports nothing for identical entries", () => {
    expect(diffEntries(base, { ...base })).toEqual([]);
  });
  it("reports a changed, an added and a removed entry", () => {
    const changed = { "CVE-2099-0001": { ...base["CVE-2099-0001"], knownRansomware: true } };
    expect(diffEntries(base, changed)).toEqual(["CVE-2099-0001"]);
    const added = { ...base, "CVE-2099-0003": { ...base["CVE-2099-0001"], cveId: "CVE-2099-0003" } };
    expect(diffEntries(base, added)).toEqual(["CVE-2099-0003"]);
    expect(diffEntries(added, base)).toEqual(["CVE-2099-0003"]);
  });
});
